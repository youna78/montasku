require('./test-task-editing.cjs');
const assert = require('node:assert/strict');
const { isHandleTaskReorderEnabled } = require('../lib/game/taskEditingUi.ts');
assert.equal(isHandleTaskReorderEnabled(new Date('2026-10-31T23:59:59.999+09:00')), false);
assert.equal(isHandleTaskReorderEnabled(new Date('2026-11-01T00:00:00+09:00')), true);
assert.equal(isHandleTaskReorderEnabled(new Date('2027-01-01T00:00:00+09:00')), true);
console.log('Task reorder UI: Japan midnight boundary and continued availability passed.');
const game = require('../lib/game/state.ts');
const tasks = Array.from({length:15}, (_, index) => ({taskId:index + 1, defaultEnabled:true, recommendedOrder:index}));
const initial = {...game.buildInitialState(tasks), freeCoins:123, completedTaskIdsToday:[2, 3]};
const before = JSON.stringify(initial);
const orderedIds = state => [...state.activeTasks].sort((a,b) => a.sortOrder-b.sortOrder).map(task => task.taskId);
const last = game.moveTaskToIndex(initial, 1, 14);
assert.equal(last.moved, true);
assert.deepEqual(orderedIds(last.nextState), [...Array.from({length:14}, (_, i) => i+2), 1]);
assert.equal(last.nextState.freeCoins, 123);
assert.deepEqual(last.nextState.completedTaskIdsToday, [2,3]);
assert.equal(JSON.stringify(initial), before, 'Preview/commit must not mutate the source state');
const first = game.moveTaskToIndex(last.nextState, 1, 0);
assert.deepEqual(orderedIds(first.nextState), orderedIds(initial));
for (const index of [-1, 15, NaN, 0.5]) assert.equal(game.moveTaskToIndex(initial, 1, index).moved, false);
assert.equal(game.moveTaskToIndex(initial, 999, 0).moved, false);
assert.equal(game.moveTaskToIndex(initial, 1, 0).nextState, initial);
console.log('Long-distance reorder: 15 tasks, both ends, progress preservation, immutable input and invalid targets passed.');
