require('./test-october-ui.cjs');
const assert = require('node:assert/strict');
const game = require('../lib/game/state.ts');
const {normalizeCustomTasks, CUSTOM_TASK_IDS} = require('../lib/game/customTasks.ts');
const {getFallbackLevelingMaster} = require('../lib/game/leveling.ts');
const custom = normalizeCustomTasks(CUSTOM_TASK_IDS.map(taskId => ({taskId,name:' 自分のタスク ',baseExp:999})));
assert.equal(custom.length,3);
assert.equal(custom[0].baseExp,2);
assert.equal(normalizeCustomTasks([{taskId:100004,name:'余分'}]).length,0);
assert.equal(normalizeCustomTasks([{taskId:100001,name:'   '}]).length,0);
const tasks = Array.from({length:4},(_,i)=>({...custom[0],taskId:i+1,defaultEnabled:true,recommendedOrder:i}));
let state = {...game.buildInitialState(tasks),hasSeenTutorial:true,hasCompletedCurrentBirth:true,customTasks:custom};
state = game.addTaskToActive(state,100001).nextState;
state = game.completeTask({state,task:custom[0],monsters:[],levelingRows:getFallbackLevelingMaster()}).nextState;
const coins = state.freeCoins;
state = game.removeTaskFromActive(state,100001).nextState;
state = game.addTaskToActive(state,100001).nextState;
const duplicate = game.completeTask({state,task:custom[0],monsters:[],levelingRows:getFallbackLevelingMaster()});
assert.equal(duplicate.alreadyCompleted,true);
assert.equal(duplicate.nextState.freeCoins,coins);
state = game.moveTaskInActive(state,100001,'up').nextState;
assert.equal(state.activeTasks.sort((a,b)=>a.sortOrder-b.sortOrder).at(-2).taskId,100001);
window.localStorage.setItem = () => {};
const restored = game.hydrateGameState(JSON.parse(JSON.stringify(state)),tasks,getFallbackLevelingMaster());
assert.deepEqual(restored.customTasks,custom);
assert.ok(restored.completedTaskIdsToday.includes(100001));
console.log('Task editing: three custom slots, fixed rewards, reorder, persistence and same-day re-add protection passed.');
